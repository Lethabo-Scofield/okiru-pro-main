#!/usr/bin/env node
/**
 * Single-source-of-truth sync for the markdown conversion helpers.
 *
 * `okiru-ai-parser` and `apps/api` are built as separate Docker images with
 * mutually isolated build contexts (the api image never copies okiru-ai-parser/,
 * and the parser image copies only its own dir), so neither a shared `packages/`
 * module nor a cross-package import can span both. The converter therefore has to
 * physically exist in each tree. To keep that from silently drifting, ONE file is
 * canonical and the other is GENERATED from it by this script:
 *
 *   canonical:  okiru-ai-parser/src/services/markdownConversion.ts   (edit here)
 *   generated:  apps/api/pipeline/extraction/documentMarkdown.ts     (do not edit)
 *
 * Run `node scripts/sync-shared-markdown.mjs` after editing the canonical file.
 * A CI guard test (apps/api/__tests__/documentMarkdown.sync.test.ts) fails if the
 * generated copy is stale, so the two can never diverge past review.
 *
 * Usage:
 *   node scripts/sync-shared-markdown.mjs          # write the generated copy
 *   node scripts/sync-shared-markdown.mjs --check   # exit 1 if the copy is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const CANONICAL = resolve(repoRoot, 'okiru-ai-parser/src/services/markdownConversion.ts');
export const GENERATED = resolve(repoRoot, 'apps/api/pipeline/extraction/documentMarkdown.ts');

const BANNER = `// @generated by scripts/sync-shared-markdown.mjs — DO NOT EDIT.
// Canonical source: okiru-ai-parser/src/services/markdownConversion.ts
// Edit the canonical file, then run: node scripts/sync-shared-markdown.mjs
// (The two services deploy as separate Docker images and cannot share a module.)
`;

/** Build the exact contents the generated file must have from the canonical source. */
export function renderGenerated() {
  const canonical = readFileSync(CANONICAL, 'utf8');
  return `${BANNER}\n${canonical}`;
}

function main() {
  const check = process.argv.includes('--check');
  const expected = renderGenerated();

  if (check) {
    let actual = '';
    try {
      actual = readFileSync(GENERATED, 'utf8');
    } catch {
      // missing file → stale
    }
    if (actual !== expected) {
      console.error('✗ apps/api documentMarkdown.ts is out of sync with the canonical parser converter.');
      console.error('  Run: node scripts/sync-shared-markdown.mjs');
      process.exit(1);
    }
    console.log('✓ shared markdown converter is in sync');
    return;
  }

  writeFileSync(GENERATED, expected);
  console.log(`✓ wrote ${GENERATED} from canonical source`);
}

// Only run when executed directly, not when imported by the guard test.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
