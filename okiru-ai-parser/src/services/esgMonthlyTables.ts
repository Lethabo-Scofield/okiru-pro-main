/** A year range the file or title states ("2025-2026", "2025/26"), as [start, end]. */
export function statedYearRange(...texts: string[]): [number, number] | null {
  for (const text of texts) {
    const m = /\b(20\d{2})\s*[-/–]\s*(20\d{2}|\d{2})\b/.exec(text ?? '');
    if (!m) continue;
    const start = Number(m[1]);
    const end = m[2].length === 2 ? 2000 + Number(m[2]) : Number(m[2]);
    if (end === start + 1) return [start, end];
  }
  return null;
}

/** How a line is named in the question and the answer. */
export function lineKey(line: Pick<MonthLine, 'label' | 'qualifier'>): string {
  return `${line.label}|${line.qualifier}`;
}

function measureCatalogue(): string {
  return Object.entries(ESG_MONTHLY_MEASURES)
    .map(([key, spec]) => `  ${key}: ${spec.what} (stored in ${spec.unit})`)
    .join('\n');
}

/**
 * How many lines one question names. Every line is asked about: a line left
 * out of the question has no answer, and a line with no answer is silently
 * not read. A table with more lines than this is asked about in parts, each
 * part on its own (cached) question; a table of up to sixteen lines asks
 * exactly the question it always has.
 */
const LINES_PER_QUESTION = 40;

async function readTable(
  model: ExtractionModel,
  table: MonthTable,
  context: { filename: string; sheetName?: string },
): Promise<TableReading | null> {
  const lines = table.lines.filter((line) => !line.isTotal);
  if (lines.length === 0) return null;
  const parts: TableReading[] = [];
  for (let at = 0; at < lines.length; at += LINES_PER_QUESTION) {
    const part = await readTableLines(model, table, lines.slice(at, at + LINES_PER_QUESTION), context);
    if (part) parts.push(part);
  }
  if (parts.length === 0) return null;
  // The first part says what the lines are and which year; every part answers its own lines.
  return { ...parts[0], lines: Object.assign({}, ...parts.map((part) => part.lines)) };
}

async function readTableLines(
  model: ExtractionModel,
  table: MonthTable,
  lines: MonthLine[],
  context: { filename: string; sheetName?: string },
): Promise<TableReading | null> {
  const sample = lines.map((line) => ({
    key: lineKey(line),
    label: line.label,
    qualifier: line.qualifier || undefined,
    first_values: line.values.filter((v) => v !== null).slice(0, 3),
  }));
  const user = [
    `FILE: ${context.filename}`,
    `SHEET: ${context.sheetName ?? ''}`,
    `TITLE: ${table.title.join(' / ') || '(none)'}`,
    `CORNER CELL: ${table.corner || '(none)'}`,
    `MONTHS: ${table.months.map((m) => MONTH_NAMES[m - 1]).join(', ')}${table.years[0] ? ` (first stated as ${table.years[0]})` : ''}`,
    table.monthUnits.length ? `UNITS UNDER THE MONTHS: ${Array.from(new Set(table.monthUnits)).join(', ')}` : '',
    table.long
      ? 'LAYOUT: one line per site AND measure. Each line\'s label is its site; its qualifier says what the line measures, ending with the unit the line states. Answer lines_are "sites" and give each line its own measure and unit.'
      : '',
    `LINES: ${JSON.stringify(sample)}`,
    'MEASURES:',
    measureCatalogue(),
    'UNITS you may name: L, kL, m3, ML, kWh, MWh, kg, t, km, other.',
    'Reply: {"lines_are":"sites"|"measures"|"other","site":string|null,"first_month_year":number|null,',
    '"lines":{"<key>":{"measure":"<measure or none>","unit":"<unit>"}}} — one entry per key given.',
  ].filter(Boolean).join('\n');

  // The FILE is part of the key: two years' dashboards share a template, and a
  // template's meaning may be reused but a document's year never is — reused,
  // last year's answer put this year's electricity a year early.
  const fingerprint = decisionFingerprint([
    'esgmonthly',
    context.filename,
    table.title.join('|'),
    table.corner,
    table.months.join(','),
    ...sample.map((s) => s.key).sort(),
  ]);

  try {
    const decision = await rememberDecision<TableReading | null>('esgmonthly', fingerprint, async () => {
      const ask = model.completeHard?.bind(model) ?? model.complete.bind(model);
      const reply = await ask(SYSTEM, user);
      const json = JSON.parse(reply.slice(reply.indexOf('{'), reply.lastIndexOf('}') + 1)) as Record<string, any>;
      const read: Record<string, LineReading> = {};
      for (const [key, value] of Object.entries((json.lines ?? {}) as Record<string, any>)) {
        const measure = String(value?.measure ?? 'none');
        read[key] = {
          measure: (measure in ESG_MONTHLY_MEASURES ? measure : 'none') as LineReading['measure'],
          unit: String(value?.unit ?? 'other'),
        };
      }
      const year = Number(json.first_month_year);
      return {
        linesAre: json.lines_are === 'measures' ? 'measures' : json.lines_are === 'other' ? 'other' : 'sites',
        site: typeof json.site === 'string' && json.site.trim() ? json.site.trim() : null,
        firstMonthYear: Number.isInteger(year) && year > 1990 && year < 2100 ? year : null,
        lines: read,
      };
    });
    const reading = decision.value;
    if (!reading) return null;
    // A file that states its year range ("DASHBOARD 2025-2026") bounds the
    // answer: the first month falls in one of those two years, whatever was said.
    const range = statedYearRange(context.filename, ...table.title, context.sheetName ?? '');
    if (range && !table.years[0] && reading.firstMonthYear !== range[0] && reading.firstMonthYear !== range[1]) {
      return { ...reading, firstMonthYear: table.months[0] >= 7 ? range[0] : range[1] };
    }
    return reading;
  } catch (err) {
    logger.warn('Monthly table could not be read', { file: context.filename, sheet: context.sheetName, reason: (err as Error).message });
    return null;
  }
}

