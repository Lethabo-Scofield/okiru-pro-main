const isBlank = (c: unknown) => c === null || c === undefined || String(c).trim() === '';
const asNumber = (c: unknown): number | null => {
  if (typeof c === 'number' && Number.isFinite(c)) return c;
  if (typeof c === 'string' && /^-?[\d\s,]*\.?\d+$/.test(c.trim())) {
    const n = Number(c.replace(/[\s,]/g, ''));
    return Number.isFinite(n) ? n : null;
  }
  return null;
};
const asText = (c: unknown) => (typeof c === 'string' ? c.replace(/\s+/g, ' ').trim() : '');

/** One line of figures beside a month run: a site (or a measure) and its numbers. */
export interface MonthLine {
  label: string;
  /** A second label beside the first — a unit ("LT", "KWH") or a landlord's name. */
  qualifier: string;
  /** Per month in the run: the figure, or null where the cell is empty. */
  values: Array<number | null>;
  isTotal: boolean;
}

export interface MonthTable {
  orientation: 'months-across' | 'months-down';
  /** Text lines above the table: its title. */
  title: string[];
  /** The cell where the line labels' header sits (often the company or site name). */
  corner: string;
  /** Unit labels stated under the months ("LPG - kg"), when the table has them. */
  monthUnits: string[];
  months: number[];
  years: Array<number | undefined>;
  lines: MonthLine[];
  /**
   * The second half of the table above it: no title of its own (the row above
   * is that table's total) and the same lines. A year split Jul–Dec / Jan–Jun is
   * one table laid out twice, and is read as one.
   */
  continues?: boolean;
}

/** Same lines in the same order — the mark of a table continued below itself. */
function sameLines(a: MonthTable, b: Pick<MonthTable, 'lines'>): boolean {
  const labels = (t: Pick<MonthTable, 'lines'>) => t.lines.filter((l) => !l.isTotal).map(lineKey).join('\n');
  return labels(a) !== '' && labels(a) === labels(b);
}

const TOTAL_LABEL = /^(grand\s+)?(sub-?)?totals?\b|^total\s/i;

function titleAbove(matrix: unknown[][], row: number): string[] {
  const title: string[] = [];
  for (let r = row - 1; r >= 0 && title.length < 3; r -= 1) {
    const cells = (matrix[r] ?? []).filter((c) => !isBlank(c));
    if (cells.length === 0) {
      if (title.length > 0) break;
      continue;
    }
    // A row of figures is the previous table, not this one's title.
    if (cells.some((c) => asNumber(c) !== null)) break;
    title.unshift(cells.map(asText).filter(Boolean).join(' · '));
  }
  return title;
}

/** Tables whose month labels run across a row. */
function tablesAcross(matrix: unknown[][]): MonthTable[] {
  const tables: MonthTable[] = [];
  for (let r = 0; r < matrix.length; r += 1) {
    const run = monthRun(matrix[r] ?? [], false);
    if (!run) continue;
    const firstCol = run.at[0];

    // A row of unit labels under the months ("LPG - kg | AMOUNT") belongs to the header.
    let dataStart = r + 1;
    let monthUnits: string[] = [];
    const under = matrix[r + 1] ?? [];
    if (run.at.every((c) => asNumber(under[c]) === null) && run.at.filter((c) => asText(under[c])).length >= run.at.length / 2) {
      monthUnits = run.at.map((c) => asText(under[c]));
      dataStart = r + 2;
    }

    const body: unknown[][] = [];
    let last = dataStart - 1;
    for (let d = dataStart; d < matrix.length; d += 1) {
      const row = matrix[d] ?? [];
      if (row.every(isBlank)) break;
      if (monthRun(row, false)) break;
      last = d;
      const values = run.at.map((c) => asNumber(row[c]));
      if (values.every((v) => v === null)) {
        // A label with no figures yet ("ALDER WAREHOUSE") is a line, not the end.
        if (row.slice(0, firstCol).some((c) => asText(c))) continue;
        break;
      }
      body.push(row);
    }
    if (body.length === 0) continue;

    // Labels are read by POSITION: the label column is the leftmost one left of
    // the months that names at least half the rows. A total row leaves it blank
    // and may still state its unit beside it ("" | "LT" | 3 | …) — read by
    // "first non-empty cell", that unit became a site called "LT".
    const textCount = (c: number) => body.filter((row) => asText(row[c])).length;
    const labelColumns = Array.from({ length: firstCol }, (_, c) => c).filter((c) => textCount(c) > 0);
    const labelCol = labelColumns.find((c) => textCount(c) * 2 >= body.length) ?? labelColumns[0] ?? -1;
    const qualifierCol = labelColumns.find((c) => c > labelCol) ?? -1;
    const lines: MonthLine[] = body.map((row) => {
      const label = labelCol >= 0 ? asText(row[labelCol]) : '';
      return {
        label,
        qualifier: qualifierCol >= 0 ? asText(row[qualifierCol]) : '',
        values: run.at.map((c) => asNumber(row[c])),
        isTotal: !label || TOTAL_LABEL.test(label),
      };
    });
    const title = titleAbove(matrix, r);
    const previous = tables[tables.length - 1];
    tables.push({
      orientation: 'months-across',
      title: title.length === 0 && previous && sameLines(previous, { lines }) ? previous.title : title,
      corner: firstCol > 0 ? asText((matrix[r] ?? [])[0]) : '',
      monthUnits,
      months: run.months,
      years: run.years,
      lines,
      continues: title.length === 0 && previous !== undefined && sameLines(previous, { lines }),
    });
    r = last;
  }
  return tables;
}

/** Tables whose months run DOWN a column (a summary sheet: a row per month, a column per measure). */
function tablesDown(matrix: unknown[][]): MonthTable[] {
  const width = matrix.reduce((w, row) => Math.max(w, row.length), 0); // not Math.max(...rows): spreading every row as an argument overflows the stack past ~120k rows
  for (let c = 0; c < width; c += 1) {
    const run = monthRun(matrix.map((row) => row[c]), true);
    if (!run) continue;
    const top = run.at[0];
    const header = top - 1;
    const group = top - 2;
    const lines: MonthLine[] = [];
    let carried = '';
    for (let k = c + 1; k < width; k += 1) {
      // A group header ("ROAD FREIGHT") spans several columns: carry it right.
      const groupLabel = group >= 0 ? asText((matrix[group] ?? [])[k]) : '';
      if (groupLabel) carried = groupLabel;
      const values = run.at.map((r) => asNumber((matrix[r] ?? [])[k]));
      if (values.filter((v) => v !== null).length < Math.ceil(run.at.length / 2)) continue;
      const own = header >= 0 ? asText((matrix[header] ?? [])[k]) : '';
      lines.push({ label: [carried, own].filter(Boolean).join(' › '), qualifier: '', values, isTotal: false });
    }
    if (lines.length === 0) continue;
    // One month column per sheet is the summary layout; a second would be a copy.
    return [{
      orientation: 'months-down',
      title: titleAbove(matrix, Math.max(0, group)),
      corner: header >= 0 ? asText((matrix[header] ?? [])[c]) : '',
      monthUnits: [],
      months: run.months,
      years: run.years,
      lines,
    }];
  }
  return [];
}

export function findMonthTables(matrix: unknown[][]): MonthTable[] {
  const across = tablesAcross(matrix);
  return across.length > 0 ? across : tablesDown(matrix);
}

/* ------------------------------------------------------------------ *
 * The one model question per table
 * ------------------------------------------------------------------ */

interface LineReading {
  measure: EsgMonthlyMeasure | 'none';
  unit: string;
}

export interface TableReading {
  /**
   * Whether each line is a SITE (rows are depots), a MEASURE of one site, or
   * something else — a vehicle, a person, an asset — which this reader does not
   * read (a vehicle register with monthly columns belongs to the register reader).
   */
  linesAre: 'sites' | 'measures' | 'other';
  /** The site a measures-table belongs to, when it names one. */
  site: string | null;
  /** The calendar year of the FIRST month, when the labels do not state it. */
  firstMonthYear: number | null;
  /** Keyed by lineKey. */
  lines: Record<string, LineReading>;
}

const SYSTEM = [
  "You read the structure of a table in a company's environmental spreadsheet for an ESG report.",
  'Its columns (or rows) are months. Each other line is a SITE (a depot, branch or warehouse), a',
  'MEASURE of one site, or something else entirely — a vehicle, a person, an asset — in which case',
  'answer lines_are "other" and nothing more. Say what each line measures, choosing ONLY from the list',
  'given, or "none" for money, tonnage, cases, counts, percentages and anything else not on the list.',
  'Give the unit the table states for that line. Work out the calendar year of the FIRST month from the',
  'sheet, title and file name (a "2025/2026" report that runs July to June starts in July 2025).',
  'Reply with JSON only.',
].join(' ');

/** A year range the file or title states ("2025-2026", "2025/26"), as [start, end]. */
export function statedYearRange(...texts: string[]): [number, number] | null {
  for (const text of texts) {
    const m = /\b(20\d{2})\s*[-/–]\s*(20\d{2}|\d{2})\b/.exec(text ?? '');
    if (!m) continue;
    const start = Number(m[1]);
    const end = m[2].length === 2 ? 2000 + Number(m[2]) : Number(m[2]);
    if (end === start + 1) return [start, end];
  }
  return null;
}

/** How a line is named in the question and the answer. */
export function lineKey(line: Pick<MonthLine, 'label' | 'qualifier'>): string {
  return `${line.label}|${line.qualifier}`;
}

function measureCatalogue(): string {
  return Object.entries(ESG_MONTHLY_MEASURES)
    .map(([key, spec]) => `  ${key}: ${spec.what} (stored in ${spec.unit})`)
    .join('\n');
}

async function readTable(
  model: ExtractionModel,
  table: MonthTable,
  context: { filename: string; sheetName?: string },
): Promise<TableReading | null> {
  const lines = table.lines.filter((line) => !line.isTotal);
  if (lines.length === 0) return null;
  const sample = lines.slice(0, 16).map((line) => ({
    key: lineKey(line),
    label: line.label,
    qualifier: line.qualifier || undefined,
    first_values: line.values.filter((v) => v !== null).slice(0, 3),
  }));
  const user = [
    `FILE: ${context.filename}`,
    `SHEET: ${context.sheetName ?? ''}`,
    `TITLE: ${table.title.join(' / ') || '(none)'}`,
    `CORNER CELL: ${table.corner || '(none)'}`,
    `MONTHS: ${table.months.map((m) => MONTH_NAMES[m - 1]).join(', ')}${table.years[0] ? ` (first stated as ${table.years[0]})` : ''}`,
    table.monthUnits.length ? `UNITS UNDER THE MONTHS: ${Array.from(new Set(table.monthUnits)).join(', ')}` : '',
    `LINES: ${JSON.stringify(sample)}`,
    'MEASURES:',
    measureCatalogue(),
    'UNITS you may name: L, kL, m3, ML, kWh, MWh, kg, t, km, other.',
    'Reply: {"lines_are":"sites"|"measures"|"other","site":string|null,"first_month_year":number|null,',
    '"lines":{"<key>":{"measure":"<measure or none>","unit":"<unit>"}}} — one entry per key given.',
  ].filter(Boolean).join('\n');

  // The FILE is part of the key: two years' dashboards share a template, and a
  // template's meaning may be reused but a document's year never is — reused,
  // last year's answer put this year's electricity a year early.
  const fingerprint = decisionFingerprint([
    'esgmonthly',
    context.filename,
    table.title.join('|'),
    table.corner,
    table.months.join(','),
    ...sample.map((s) => s.key).sort(),
  ]);

  try {
    const decision = await rememberDecision<TableReading | null>('esgmonthly', fingerprint, async () => {
      const ask = model.completeHard?.bind(model) ?? model.complete.bind(model);
      const reply = await ask(SYSTEM, user);
      const json = JSON.parse(reply.slice(reply.indexOf('{'), reply.lastIndexOf('}') + 1)) as Record<string, any>;
      const read: Record<string, LineReading> = {};
      for (const [key, value] of Object.entries((json.lines ?? {}) as Record<string, any>)) {
        const measure = String(value?.measure ?? 'none');
        read[key] = {
          measure: (measure in ESG_MONTHLY_MEASURES ? measure : 'none') as LineReading['measure'],
          unit: String(value?.unit ?? 'other'),
        };
      }
      const year = Number(json.first_month_year);
      return {
        linesAre: json.lines_are === 'measures' ? 'measures' : json.lines_are === 'other' ? 'other' : 'sites',
        site: typeof json.site === 'string' && json.site.trim() ? json.site.trim() : null,
        firstMonthYear: Number.isInteger(year) && year > 1990 && year < 2100 ? year : null,
        lines: read,
      };
    });
    const reading = decision.value;
    if (!reading) return null;
    // A file that states its year range ("DASHBOARD 2025-2026") bounds the
    // answer: the first month falls in one of those two years, whatever was said.
    const range = statedYearRange(context.filename, ...table.title, context.sheetName ?? '');
    if (range && !table.years[0] && reading.firstMonthYear !== range[0] && reading.firstMonthYear !== range[1]) {
      return { ...reading, firstMonthYear: table.months[0] >= 7 ? range[0] : range[1] };
    }
    return reading;
  } catch (err) {
    logger.warn('Monthly table could not be read', { file: context.filename, sheet: context.sheetName, reason: (err as Error).message });
    return null;
  }
}

