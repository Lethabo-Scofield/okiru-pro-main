/**
 * Read a site × month table as monthly figures — deterministically.
 *
 * WHY THIS EXISTS
 *
 * The way companies actually keep environmental data is a dashboard: one sheet
 * per theme, a block per measure ("FUEL LITRES", "KM", "GENERATOR FUEL"), a row
 * per depot, a column per month. The ESG workbook's own grids have exactly that
 * shape — Scope 1A diesel, Scope 2 electricity, water — site by month.
 *
 * The parser read those sheets as if they were one flat document: the model
 * was asked for ONE `fuel_litres`, ONE `site_name`, ONE billing period per
 * sheet. A sheet holding 45 figures cannot answer that, so it gave one or none,
 * and the blocks below the first were flattened into stray rows under the
 * first block's header. A dashboard holding a year of depot data placed nothing.
 *
 * THE SPLIT OF LABOUR — the same one the register readers use:
 *   - CODE finds the structure: a run of consecutive month labels (across a row
 *     or down a column), the data rows or columns beside it, the title lines
 *     above it, the unit each line states, and which lines are totals.
 *   - The MODEL answers one closed question per table — which measure each line
 *     is, from a fixed list, in which unit, and which year the first month falls
 *     in — cached on the table's shape, so a template is asked about once.
 *   - CODE reads every number. Never a total row: a total is the place a
 *     spreadsheet goes wrong (a July total typed over as `3`, a November SUM
 *     that skips a depot), and the depot rows are the evidence.
 *
 * Each figure becomes one fact — measure, site as written, month, value, unit —
 * emitted as rows of `esg_monthly_rows`. Which grid, which depot row and which
 * month column it lands in is the workbook's decision, made on the web against
 * the company's own sites and reporting year. This file only says what the
 * document states.
 */
import { createLogger } from '../logger.js';
import type { DocumentExtraction, ExtractionModel } from './aiExtraction.js';
import { decisionFingerprint, rememberDecision } from './semanticDecisionCache.js';

const logger = createLogger('EsgMonthlyTables');

/** The monthly measures the ESG workbook keeps, and the unit each is stored in. */
export const ESG_MONTHLY_MEASURES = {
  'fleet.diesel_litres': { unit: 'L', what: 'diesel used by the delivery / road-freight fleet (trucks), litres' },
  'fleet.business_car_petrol_litres': { unit: 'L', what: 'fuel used by company or business cars (not freight trucks), litres' },
  'fleet.distance_km': { unit: 'km', what: 'distance driven by the fleet, kilometres' },
  'fleet.external_diesel_issued_litres': {
    unit: 'L',
    what: 'diesel issued from the company\'s own tanks to vehicles OUTSIDE its fleet ("external vehicles", contractors, third parties), litres',
  },
  'energy.generator_diesel_litres': { unit: 'L', what: 'diesel burned in standby generators, litres' },
  'energy.lpg_kg': { unit: 'kg', what: 'LPG / forklift gas, kilograms' },
  'energy.electricity_kwh': { unit: 'kWh', what: 'grid electricity consumed, kWh' },
  'energy.solar_kwh_generated': { unit: 'kWh', what: 'electricity generated by on-site solar, kWh' },
  'water.kl': { unit: 'kL', what: 'water consumed, kilolitres' },
} as const;

export type EsgMonthlyMeasure = keyof typeof ESG_MONTHLY_MEASURES;

/** Units the model may name, and what one of them is in the measure's stored unit. */
const UNIT_FACTORS: Record<string, Record<string, number>> = {
  L: { L: 1, kL: 1000 },
  kL: { kL: 1, L: 0.001, m3: 1, ML: 1000 },
  kWh: { kWh: 1, MWh: 1000 },
  kg: { kg: 1, t: 1000 },
  km: { km: 1 },
};

export interface EsgMonthlyFact {
  measure: EsgMonthlyMeasure;
  /** The site exactly as the document names it; null for a company-wide line. */
  site: string | null;
  /** Last day of the month, ISO. */
  period_end: string;
  value: number;
  unit: string;
}

/* ------------------------------------------------------------------ *
 * Month labels
 * ------------------------------------------------------------------ */

const MONTH_NAMES = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
const FULL_MONTH_NAMES = [
  'january', 'february', 'march', 'april', 'may', 'june',
  'july', 'august', 'september', 'october', 'november', 'december',
];

/** "JUL", "July", "Jul-25", "2025-07", or an Excel date serial for a month → month (+ year). */
export function readMonthLabel(cell: unknown, allowSerial: boolean): { month: number; year?: number } | null {
  if (typeof cell === 'number') {
    // Excel serials between 2000 and 2100; a serial is only trusted down a
    // column of consecutive months, which the caller checks.
    if (!allowSerial || !Number.isInteger(cell) || cell < 36526 || cell > 73051) return null;
    const date = new Date(Math.round((cell - 25569) * 86400 * 1000));
    return { month: date.getUTCMonth() + 1, year: date.getUTCFullYear() };
  }
  if (typeof cell !== 'string') return null;
  const text = cell.trim().toLowerCase().replace(/\.$/, '');
  const named = /^([a-z]{3,9})(?:[\s\-/']+(\d{2}|\d{4}))?$/.exec(text);
  if (named) {
    const index = MONTH_NAMES.indexOf(named[1].slice(0, 3));
    // "march" and "mar" yes; "marketing" no: the word must BE a month name.
    if (index < 0 || !(named[1].length === 3 || FULL_MONTH_NAMES[index].startsWith(named[1]) || named[1] === 'sept')) return null;
    const year = named[2] ? (named[2].length === 2 ? 2000 + Number(named[2]) : Number(named[2])) : undefined;
    return { month: index + 1, year };
  }
  const iso = /^(\d{4})[-/](\d{1,2})$/.exec(text);
  if (iso && Number(iso[2]) >= 1 && Number(iso[2]) <= 12) return { month: Number(iso[2]), year: Number(iso[1]) };
  return null;
}

const nextMonth = (m: number) => (m % 12) + 1;

interface MonthRun {
  /** Index of each month cell along the line, in order. */
  at: number[];
  months: number[];
  years: Array<number | undefined>;
}

/**
 * The longest run of CONSECUTIVE months along a line of cells, gaps allowed
 * (a month column followed by its "AMOUNT" column). Three or more is a header;
 * consecutiveness is what tells it from a sentence that mentions March.
 */
function monthRun(cells: unknown[], allowSerial: boolean): MonthRun | null {
  let best: MonthRun | null = null;
  let current: MonthRun | null = null;
  for (let i = 0; i < cells.length; i += 1) {
    const label = readMonthLabel(cells[i], allowSerial);
    if (!label) continue;
    if (current && label.month === nextMonth(current.months[current.months.length - 1])) {
      current.at.push(i);
      current.months.push(label.month);
      current.years.push(label.year);
    } else {
      current = { at: [i], months: [label.month], years: [label.year] };
    }
    if (!best || current.at.length > best.at.length) {
      best = { at: [...current.at], months: [...current.months], years: [...current.years] };
    }
  }
  return best && best.at.length >= 3 ? best : null;
}

